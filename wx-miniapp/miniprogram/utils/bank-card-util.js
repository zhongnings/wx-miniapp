/**
 * 根据银行卡号识别银行
 * @param {string} cardNumber - 银行卡号（可以包含空格）
 * @returns {string|null} - 银行名称，如果无法识别则返回 null
 */
function identifyBank(cardNumber) {
  if (!cardNumber) {
    return null;
  }
  
  // 移除空格和其他非数字字符
  const cleanCardNumber = cardNumber.replace(/\D/g, '');
  
  // 银行卡号至少需要6位才能识别
  if (cleanCardNumber.length < 6) {
    return null;
  }

  // 优先尝试长前缀精确匹配（8/7/6 位）
  const exactPrefixLengths = [8, 7, 6];
  for (const len of exactPrefixLengths) {
    if (cleanCardNumber.length >= len) {
      const prefix = cleanCardNumber.substring(0, len);
      if (BANK_BIN_MAP[prefix]) {
        return BANK_BIN_MAP[prefix];
      }
    }
  }

  // 兜底：使用 5/4 位前缀做“唯一归属”匹配，避免误识别
  // 仅当候选 BIN 对应的银行唯一时返回；若存在多个银行则返回 null
  const fallbackPrefixLengths = [5, 4];
  for (const len of fallbackPrefixLengths) {
    if (cleanCardNumber.length < len) {
      continue;
    }
    const prefix = cleanCardNumber.substring(0, len);
    const candidateBanks = new Set();
    Object.keys(BANK_BIN_MAP).forEach((binKey) => {
      if (binKey.startsWith(prefix)) {
        candidateBanks.add(BANK_BIN_MAP[binKey]);
      }
    });
    if (candidateBanks.size === 1) {
      return Array.from(candidateBanks)[0];
    }
  }

  return null;
}

/**
 * 格式化银行卡号（每4位添加一个空格）
 * @param {string} cardNumber - 银行卡号
 * @returns {string} - 格式化后的银行卡号
 */
function formatCardNumber(cardNumber) {
  if (!cardNumber) {
    return '';
  }
  
  // 移除所有空格
  const cleanNumber = cardNumber.replace(/\s/g, '');
  
  // 每4位添加一个空格
  return cleanNumber.replace(/(.{4})/g, '$1 ').trim();
}

/**
 * 验证银行卡号格式
 * @param {string} cardNumber - 银行卡号
 * @returns {boolean} - 是否有效
 */
function validateCardNumber(cardNumber) {
  if (!cardNumber) {
    return false;
  }
  
  const cleanNumber = cardNumber.replace(/\D/g, '');
  
  // 银行卡号长度通常在16-19位之间
  if (cleanNumber.length < 16 || cleanNumber.length > 19) {
    return false;
  }
  
  // Luhn 算法验证（可选，更严格的验证）
  return luhnCheck(cleanNumber);
}

/**
 * Luhn 算法验证银行卡号
 * @param {string} cardNumber - 纯数字银行卡号
 * @returns {boolean} - 是否通过验证
 */
function luhnCheck(cardNumber) {
  let sum = 0;
  let isEven = false;
  
  // 从右往左遍历
  for (let i = cardNumber.length - 1; i >= 0; i--) {
    let digit = parseInt(cardNumber.charAt(i), 10);
    
    if (isEven) {
      digit *= 2;
      if (digit > 9) {
        digit -= 9;
      }
    }
    
    sum += digit;
    isEven = !isEven;
  }
  
  return (sum % 10) === 0;
}

